// Builds the plugin reference (docs/site/references.md). Each page joins a written half, in
// src/content/reference/, with facts read from the code (referenceFacts.mjs), and lands in a Git-ignored
// folder of the docs collection, so it gets the sidebar and search like any written page.
//
//   node scripts/reference.mjs    rewrites src/content/docs/docs/build-plugins/reference/
//
// The site's `dev`, `build`, and `lint` scripts run it first. A page with facts and no written half, or
// a written half whose facts marker is missing, fails.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { referenceFacts } from './referenceFacts.mjs'
import { PLUGIN_API_MAJOR } from '@acorn/protocol/plugin/apiVersion.ts'

const SITE = fileURLToPath(new URL('../', import.meta.url))
const WRITTEN = join(SITE, 'src/content/reference')
const GENERATED = join(SITE, 'src/content/docs/docs/build-plugins/reference')
const DOCS = join(SITE, 'src/content/docs')
const COMPONENTS = join(SITE, 'src/components')
const MARKER = '{/* facts */}'
// Written in an example where the plugin API major goes, so no page holds the number itself.
const API_MAJOR = '@API_MAJOR@'
// The components a written half may use. They're imported into every page, so a written half names
// none itself and moving a page never breaks an import path.
const PAGE_COMPONENTS = ['ApiMajor', 'Badge', 'ReferenceTable', 'Snapshot', 'Specimen']

/** Every written half, by its path under the reference folder without the extension. */
function readWritten(dir = WRITTEN) {
  return new Map(
    readdirSync(dir, { recursive: true })
      .filter((name) => /\.mdx?$/.test(name))
      .map((name) => [name.replace(/\.mdx?$/, ''), readFileSync(join(dir, name), 'utf8')]),
  )
}

// A link to a docs page that's still a draft would fail a production build, so it keeps its words and
// loses the link until that page publishes. Links to generated reference pages always resolve.
function unlinkDrafts(text, pages) {
  return text.replace(/\[([^\]]+)\]\((\/docs\/[^)#\s]*)(#[^)\s]*)?\)/g, (link, words, url) => {
    const slug = url.replace(/^\/|\/$/g, '')
    if (slug.startsWith('docs/build-plugins/reference/')) {
      if (!pages.has(slug.slice('docs/build-plugins/reference/'.length)))
        throw new Error(`${link} links to a reference page that doesn't exist.`)
      return link
    }
    const file = ['.md', '.mdx', '/index.md', '/index.mdx'].map((ending) => join(DOCS, `${slug}${ending}`)).find(existsSync)
    if (!file) throw new Error(`${link} links to a docs page that doesn't exist.`)
    return /^draft: true$/m.test(readFileSync(file, 'utf8')) ? words : link
  })
}

/** The pages to write, by path under the reference folder. Throws on any page that can't be built. */
function buildReference({ facts = referenceFacts(), written = readWritten() } = {}) {
  const problems = Object.keys(facts)
    .filter((page) => !written.has(page))
    .map((page) => `${page} has facts from the code and no written half. Add src/content/reference/${page}.mdx.`)
  const pages = new Map()
  for (const [page, text] of written) {
    const [, frontmatter, body] = text.match(/^(---\n[\s\S]*?\n---\n)([\s\S]*)$/) ?? []
    if (!frontmatter) {
      problems.push(`${page} has no frontmatter.`)
      continue
    }
    if (/^import /m.test(body.replace(/^```[\s\S]*?^```/gm, ''))) problems.push(`${page} imports a component. Use one of ${PAGE_COMPONENTS.join(', ')}.`)
    const markers = body.split(MARKER).length - 1
    if (facts[page] === undefined ? markers !== 0 : markers !== 1)
      problems.push(
        facts[page] === undefined
          ? `${page} has a ${MARKER} marker and no facts to put there.`
          : `${page} needs exactly one ${MARKER} marker, where its facts go. It has ${markers}.`,
      )
    pages.set(page, { frontmatter, body })
  }
  if (problems.length) throw new Error(problems.join('\n'))

  return new Map(
    [...pages].map(([page, { frontmatter, body }]) => {
      const from = dirname(join(GENERATED, page))
      const imports = PAGE_COMPONENTS.map(
        (name) => `import ${name} from '${relative(from, join(COMPONENTS, `${name}.astro`))}'`,
      ).join('\n')
      const filled = unlinkDrafts(body.replace(MARKER, () => facts[page] ?? ''), pages).replaceAll(API_MAJOR, PLUGIN_API_MAJOR)
      const notice = `{/* Generated by apps/site/scripts/reference.mjs from src/content/reference/${page}.mdx. Edit that file. */}`
      return [`${page}.mdx`, `${frontmatter}\n${imports}\n\n${notice}\n${filled}`]
    }),
  )
}

/** Replaces the generated folder with a fresh build of every page. */
function writeReference(pages = buildReference()) {
  rmSync(GENERATED, { recursive: true, force: true })
  for (const [file, text] of pages) {
    mkdirSync(dirname(join(GENERATED, file)), { recursive: true })
    writeFileSync(join(GENERATED, file), text)
  }
  return pages.size
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  console.log(`Wrote ${writeReference()} plugin reference pages.`)
}
