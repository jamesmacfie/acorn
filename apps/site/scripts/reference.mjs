// Builds the generated docs pages (docs/site/references.md): the plugin reference and the components.
// Each page joins a written half with facts read from the code (referenceFacts.mjs and
// componentFacts.mjs), and lands in a Git-ignored folder of the docs collection, so it gets the
// sidebar and search like any written page. BOOKS in books.mjs lists the folders.
//
//   node scripts/reference.mjs    rewrites every generated folder
//
// The site's `dev`, `build`, and `lint` scripts run it first. A page with facts and no written half, or
// a written half whose facts marker is missing, fails.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { BOOKS } from './books.mjs'
import { componentFacts } from './componentFacts.mjs'
import { referenceFacts } from './referenceFacts.mjs'
import { PLUGIN_API_MAJOR } from '@acorn/protocol/plugin/apiVersion.ts'

const SITE = fileURLToPath(new URL('../', import.meta.url))
const DOCS = join(SITE, 'src/content/docs')
const COMPONENTS = join(SITE, 'src/components')
const MARKER = '{/* facts */}'
// Written in an example where the plugin API major goes, so no page holds the number itself.
const API_MAJOR = '@API_MAJOR@'
const FACTS = { 'plugin reference': referenceFacts, components: componentFacts }

/** Every written half in a folder, by its path under the folder without the extension. */
export function readWritten(dir) {
  return new Map(
    readdirSync(dir, { recursive: true })
      .filter((name) => /\.mdx?$/.test(name))
      .map((name) => [name.replace(/\.mdx?$/, ''), readFileSync(join(dir, name), 'utf8')]),
  )
}

/** The pages each book will write, by its docs folder, for checking a link into a generated page. */
const generatedPages = () => new Map(BOOKS.map((book) => [book.docs, new Set(readWritten(join(SITE, book.written)).keys())]))

// A link to a docs page that's still a draft would fail a production build, so it keeps its words and
// loses the link until that page publishes. A link to a generated page must name one that's written.
function unlinkDrafts(text, generated) {
  return text.replace(/\[([^\]]+)\]\((\/docs\/[^)#\s]*)(#[^)\s]*)?\)/g, (link, words, url) => {
    const slug = url.replace(/^\/|\/$/g, '')
    for (const [docs, pages] of generated) {
      if (!slug.startsWith(`${docs}/`)) continue
      if (!pages.has(slug.slice(docs.length + 1))) throw new Error(`${link} links to a generated page that doesn't exist.`)
      return link
    }
    const file = ['.md', '.mdx', '/index.md', '/index.mdx'].map((ending) => join(DOCS, `${slug}${ending}`)).find(existsSync)
    if (!file) throw new Error(`${link} links to a docs page that doesn't exist.`)
    return /^draft: true$/m.test(readFileSync(file, 'utf8')) ? words : link
  })
}

/** One book's pages, by path under its docs folder. Throws on any page that can't be built. */
export function buildBook(
  book,
  { facts = FACTS[book.name](), written = readWritten(join(SITE, book.written)), generated = generatedPages() } = {},
) {
  const problems = Object.keys(facts)
    .filter((page) => !written.has(page))
    .map((page) => `${page} has facts from the code and no written half. Add ${book.written}/${page}.mdx.`)
  const pages = new Map()
  for (const [page, text] of written) {
    const [, frontmatter, body] = text.match(/^(---\n[\s\S]*?\n---\n)([\s\S]*)$/) ?? []
    if (!frontmatter) {
      problems.push(`${page} has no frontmatter.`)
      continue
    }
    if (/^import /m.test(body.replace(/^```[\s\S]*?^```/gm, ''))) problems.push(`${page} imports a component. Use one of ${book.components.join(', ')}.`)
    const markers = body.split(MARKER).length - 1
    if (facts[page] === undefined ? markers !== 0 : markers !== 1)
      problems.push(
        facts[page] === undefined
          ? `${page} has a ${MARKER} marker and no facts to put there.`
          : `${page} needs exactly one ${MARKER} marker, where its facts go. It has ${markers}.`,
      )
    pages.set(page, { frontmatter, body })
  }
  if (problems.length) throw new Error(problems.join('\n'))

  const folder = join(DOCS, book.docs)
  return new Map(
    [...pages].map(([page, { frontmatter, body }]) => {
      const from = dirname(join(folder, page))
      const imports = book.components
        .map((name) => `import ${name} from '${relative(from, join(COMPONENTS, `${name}.astro`))}'`)
        .join('\n')
      const filled = unlinkDrafts(body.replace(MARKER, () => facts[page] ?? ''), generated).replaceAll(API_MAJOR, PLUGIN_API_MAJOR)
      const notice = `{/* Generated by apps/site/scripts/reference.mjs from ${book.written}/${page}.mdx. Edit that file. */}`
      return [`${page}.mdx`, `${frontmatter}\n${imports}\n\n${notice}\n${filled}`]
    }),
  )
}

/** Replaces a book's generated folder with a fresh build of every page. */
function writeBook(book) {
  const pages = buildBook(book)
  const folder = join(DOCS, book.docs)
  rmSync(folder, { recursive: true, force: true })
  for (const [file, text] of pages) {
    mkdirSync(dirname(join(folder, file)), { recursive: true })
    writeFileSync(join(folder, file), text)
  }
  return pages.size
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const book of BOOKS) console.log(`Wrote ${writeBook(book)} ${book.name} pages.`)
}
