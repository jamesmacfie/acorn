  'that changes each time the workflow runs, and give it a description, because that is the label on',
  'the box the person fills in.',
  '',
  '### A step',
  '',
  '{',
  '  "id": "reproduce",',
  '  "name": "reproduce",',
  '  "kind": "agent",',
  '  "after": ["plan"],',
  '  "prompt": "Reproduce the failure and say which command shows it.",',
  '  "isolation": "shared",',
  '  "inputs": "append"',
  '}',
  '',
  'A step id is stable and unique within its definition. A name is a human-readable label and can contain spaces.',
  'Edges, branches and references identify a step by id. Never change an existing id when renaming a step.',
