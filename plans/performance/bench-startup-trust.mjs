import fs from 'node:fs';
import { syncBuiltinESMExports } from 'node:module';
import { performance } from 'node:perf_hooks';
const repo=process.cwd(), root=fs.mkdtempSync('/tmp/acorn-startup-trust-');
let writes=0,fsyncs=0,fsyncMs=0,reads=0,readBytes=0;
const original={write:fs.writeSync,fsync:fs.fsyncSync,read:fs.readFileSync};
fs.writeSync=(...a)=>{writes++;return original.write(...a);};
fs.fsyncSync=(...a)=>{fsyncs++;const t=performance.now();try{return original.fsync(...a);}finally{fsyncMs+=performance.now()-t;}};
fs.readFileSync=(...a)=>{const v=original.read(...a);reads++;readBytes+=Buffer.byteLength(v);return v;};
syncBuiltinESMExports();
const {PluginCache}=await import(`${repo}/packages/custody/src/plugins/pluginCache.ts`);
const {PluginTrustStore}=await import(`${repo}/packages/custody/src/plugins/pluginTrustStore.ts`);
const {trustBundledClientPlugins}=await import(`${repo}/packages/custody/src/plugins/bundledPluginTrust.ts`);
const cache=new PluginCache(root,{fetch(){throw Error('unexpected fetch');}}), trust=new PluginTrustStore(root);
const run=(version)=>{writes=0;fsyncs=0;fsyncMs=0;reads=0;readBytes=0;const t=performance.now();const ids=trustBundledClientPlugins(process.argv[2],version,cache,trust);return{version,ms:+(performance.now()-t).toFixed(2),writes,fsyncs,fsyncMs:+fsyncMs.toFixed(2),reads,readBytes,accepted:ids.length};};
console.log(JSON.stringify([run('1'),run('1'),run('1'),run('2'),run('2')],null,2));
fs.rmSync(root,{recursive:true,force:true});
